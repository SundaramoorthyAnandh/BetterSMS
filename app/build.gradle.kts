// Release signing comes from environment variables so no secret ever lands in git.
// Without them, the release APK is signed with the local debug key so it can still be sideloaded.
val releaseKeystore: String? = System.getenv("BETTERSMS_KEYSTORE")

android {
    namespace = "com.bettersms.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.bettersms.app"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("BETTERSMS_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("BETTERSMS_KEY_ALIAS")
                keyPassword = System.getenv("BETTERSMS_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (releaseKeystore != null) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
        unitTests.all { test ->
            // Optional Maven mirror for Robolectric's runtime jars (e.g. behind rate-limited networks).
            System.getenv("ROBOLECTRIC_REPO_URL")?.let { test.systemProperty("robolectric.dependency.repo.url", it) }
        }
    }
    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

